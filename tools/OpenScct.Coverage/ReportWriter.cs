using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Text.Json;

namespace OpenScct.Coverage;

/// <summary>Writes docs/progress/COVERAGE.md, coverage.json and the history.csv row. Output depends only on the
/// inputs (no clock, no machine paths), so two runs over the same inputs give the same bytes.</summary>
internal static class ReportWriter
{
    private const int MarkdownListCap = 150;

    private static readonly UnitStatus[] Levels = [UnitStatus.Specced, UnitStatus.Ported, UnitStatus.Verified];

    public static string Markdown(CoverageResult r)
    {
        var md = new StringBuilder();
        IReadOnlyList<UnitState> all = r.Units;
        var slice = all.Where(s => s.Unit!.Slice).ToList();
        Bucket total = Bucket.Total("All units", all);
        Bucket sliceTotal = Bucket.Total("SteeE slice", slice);

        md.AppendLine("# Coverage");
        md.AppendLine();
        md.AppendLine("Generated by `tools/OpenScct.Coverage` (`dotnet run --project tools/OpenScct.Coverage`). Do not edit by hand; the rules");
        md.AppendLine("are in `tools/OpenScct.Coverage/README.md` and the out-of-scope entries in `coverage/status.yaml`.");
        md.AppendLine();
        md.AppendLine("Statuses: **specced** (listed in a spec's `Units:`), **ported** (C# carries `[PortOf]`, `[Uc]` or");
        md.AppendLine("`[UcNative]` for it, or the class skeleton generator emitted the class defaults), **verified** (ported and");
        md.AppendLine("covered by a difftest scenario whose golden passes in the local runner report), **n-a** (out of scope).");
        md.AppendLine("Each level includes the ones above it. Percentages are of in-scope units; **weighted** percentages are of");
        md.AppendLine("in-scope bytecode bytes (`script_size`), so default properties and replication members (no bytecode)");
        md.AppendLine("count in the unit columns only.");
        md.AppendLine();

        md.AppendLine("## Summary");
        md.AppendLine();
        AppendTable(md, "Scope", [total, sliceTotal], b => b.Key);
        md.AppendLine();
        AppendInputs(md, r);

        md.AppendLine("## By package");
        md.AppendLine();
        AppendTable(md, "Package", Bucket.GroupBy(all, s => s.Unit!.Package), b => b.Key, total);
        md.AppendLine();

        md.AppendLine("## By unit kind");
        md.AppendLine();
        AppendTable(md, "Kind", Bucket.GroupBy(all, s => s.Unit!.Kind), b => "`" + b.Key + "`", total);
        md.AppendLine();

        md.AppendLine("## By subsystem");
        md.AppendLine();
        md.AppendLine("Subsystems are the inventory's guess from names. Sorted by in-scope bytes.");
        md.AppendLine();
        AppendTable(md, "Subsystem", Bucket.GroupBy(all, s => s.Unit!.Subsystem)
            .OrderByDescending(b => b.InScopeBytes).ThenBy(b => b.Key, StringComparer.Ordinal).ToList(), b => b.Key, total);
        md.AppendLine();

        md.AppendLine("## SteeE slice");
        md.AppendLine();
        md.AppendLine("Classes the SteeE Story 2v2 slice needs (inventory `slice`): `listed` by the plan, placed in `steee`,");
        md.AppendLine("spawned at `runtime`, or an `ancestor` of those.");
        md.AppendLine();
        AppendTable(md, "Reason", Bucket.GroupBy(slice, s => s.Unit!.SliceReason ?? "?"), b => b.Key, sliceTotal);
        md.AppendLine();
        AppendTable(md, "Class", Bucket.GroupBy(slice, s => s.Unit!.ClassPath)
            .OrderByDescending(b => b.InScopeBytes).ThenBy(b => b.Key, StringComparer.Ordinal).ToList(),
            b => $"{b.Key} ({slice.First(s => s.Unit!.ClassPath == b.Key).Unit!.SliceReason})");
        md.AppendLine();

        md.AppendLine("## Out of scope");
        md.AppendLine();
        md.AppendLine("| # | Globs | Units | Reason |");
        md.AppendLine("|---|---|---|---|");
        foreach (NaEntry e in r.Inputs.Status.Na)
        {
            md.AppendLine($"| {e.Index} | {string.Join(" ", e.Globs.Select(g => "`" + g.Pattern + "`"))} | {N(r.NaMatches.GetValueOrDefault(e.Index))} | {Cell(e.Reason)} |");
        }

        md.AppendLine();

        md.AppendLine("## Scenarios");
        md.AppendLine();
        if (r.Inputs.Report is null)
        {
            md.AppendLine("No local runner report, so no unit is verified by a scenario here. The report is");
            md.AppendLine("`local/difftest/sim/report.json`, written by `tests/OpenScct.DiffTest` where goldens and converted content exist.");
            md.AppendLine();
        }

        md.AppendLine("| Scenario | Covers | Golden | Units verified |");
        md.AppendLine("|---|---|---|---|");
        foreach (ScenarioInfo sc in r.Inputs.Scenarios)
        {
            bool? pass = r.ScenarioResults.GetValueOrDefault(sc.Id);
            int verified = r.Units.Concat(r.Extra).Count(s => s.Status == UnitStatus.Verified && s.PassingScenarios.Contains(sc.Id));
            string result = pass switch { true => "pass", false => "fail", null => "no result" };
            md.AppendLine($"| {sc.Id} | {sc.Covers.Count} | {result} | {verified} |");
        }

        md.AppendLine();

        AppendExtra(md, r);

        md.AppendLine("## By class");
        md.AppendLine();
        foreach (string pkg in Inventory.Packages)
        {
            var units = all.Where(s => s.Unit!.Package == pkg).ToList();
            if (units.Count == 0)
            {
                continue;
            }

            var classes = Bucket.GroupBy(units, s => s.Unit!.Class);
            var allNa = classes.Where(b => b.InScopeUnits == 0).Select(b => b.Key).ToList();
            md.AppendLine($"### {pkg}");
            md.AppendLine();
            AppendTable(md, "Class", classes.Where(b => b.InScopeUnits > 0).ToList(), b => b.Key, Bucket.Total(pkg, units));
            if (allNa.Count > 0)
            {
                md.AppendLine();
                md.AppendLine($"Wholly n-a: {string.Join(", ", allNa)}.");
            }

            md.AppendLine();
        }

        md.AppendLine("## Issues");
        md.AppendLine();
        AppendList(md, "Errors", r.Errors, "CI should fail on these: ids that are not in the inventory, n-a entries without a reason, missing spec files.");
        AppendList(md, "Warnings", r.Warnings, null);
        AppendList(md, "Spec ids not in the inventory", r.UnknownSpecIds, "Ids under a spec's `Units:` that name no inventory unit (renamed, inherited or misspelled).");
        return md.ToString();
    }

    private static void AppendInputs(StringBuilder md, CoverageResult r)
    {
        CoverageInputs i = r.Inputs;
        long bytes = i.Inventory.Units.Sum(u => u.Weight);
        md.AppendLine("Inputs:");
        md.AppendLine();
        md.AppendLine($"- Inventory `re/inventory/inventory.json` ({i.Inventory.Format}): {N(i.Inventory.Units.Count)} units, {N(bytes)} bytecode bytes.");
        md.AppendLine($"- Assemblies: {string.Join(", ", i.Assemblies.Select(a => a.Name).Order(StringComparer.Ordinal))}; {N(r.AttributeCount)} provenance attributes, " +
                      $"{N(i.Assemblies.Sum(a => a.GeneratedClasses.Count))} generated class skeletons.");
        md.AppendLine($"- `coverage/status.yaml`: {N(i.Status.Na.Count)} n-a entries, {N(i.Status.Units.Count)} single-unit entries.");
        md.AppendLine($"- Specs: {N(i.Specs.Count)} unit ids in the `Units:` lists of {N(i.Specs.Select(s => s.SpecFile).Distinct(StringComparer.Ordinal).Count())} files.");
        int passing = r.ScenarioResults.Values.Count(v => v == true);
        string report = i.Report is null
            ? "no local runner report (verified needs it)"
            : $"local runner report with {N(i.Report.Count)} rows, {passing} of {i.Scenarios.Count} scenarios pass ({(i.AllTimings ? "every timing" : Scenarios.GateTiming + " gate")})";
        md.AppendLine($"- Scenarios: {N(i.Scenarios.Count)} with {N(i.Scenarios.Sum(s => s.Covers.Count))} covers entries; {report}.");
        md.AppendLine($"- Issues: {N(r.Errors.Count)} errors, {N(r.Warnings.Count)} warnings, {N(r.UnknownSpecIds.Count)} spec ids not in the inventory.");
        md.AppendLine();
    }

    private static void AppendExtra(StringBuilder md, CoverageResult r)
    {
        md.AppendLine("## Engine, format and Reloaded units");
        md.AppendLine();
        md.AppendLine("Units outside the script inventory, known only from the specs and the ports (`eng:` native engine code, `fmt:`");
        md.AppendLine("file formats, `rl:` Reloaded.Core behaviour). There is no full list of them yet, so these are counts, not shares.");
        md.AppendLine();
        md.AppendLine("| Group | Units | Specced+ | Ported+ | Verified |");
        md.AppendLine("|---|---|---|---|---|");
        foreach (Bucket b in Bucket.GroupBy(r.Extra, s => ExtraGroup(s.Id)))
        {
            md.AppendLine($"| {b.Key} | {N(b.Units)} | {N(b.UnitsAtLeast(UnitStatus.Specced))} | {N(b.UnitsAtLeast(UnitStatus.Ported))} | {N(b.UnitsAtLeast(UnitStatus.Verified))} |");
        }

        Bucket t = Bucket.Total("all", r.Extra);
        md.AppendLine($"| **all** | {N(t.Units)} | {N(t.UnitsAtLeast(UnitStatus.Specced))} | {N(t.UnitsAtLeast(UnitStatus.Ported))} | {N(t.UnitsAtLeast(UnitStatus.Verified))} |");
        md.AppendLine();
    }

    /// <summary><c>eng:ASBasePawn::physWalking</c> groups as <c>eng:ASBasePawn</c>, <c>rl:input.pad</c> as <c>rl:input</c>.</summary>
    internal static string ExtraGroup(string id)
    {
        int colon = id.IndexOf(':', StringComparison.Ordinal);
        string kind = id[..colon];
        string body = id[(colon + 1)..];
        int sep = body.IndexOf("::", StringComparison.Ordinal);
        if (sep < 0)
        {
            sep = body.IndexOf('.', StringComparison.Ordinal);
        }

        return kind + ":" + (sep > 0 ? body[..sep] : body);
    }

    private static void AppendTable(StringBuilder md, string first, IReadOnlyList<Bucket> rows, Func<Bucket, string> label, Bucket? totalRow = null)
    {
        md.AppendLine($"| {first} | Units | n-a | Specced+ | Ported+ | Verified | Bytes in scope | Specced+ w | Ported+ w | Verified w |");
        md.AppendLine("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
        foreach (Bucket b in rows)
        {
            md.AppendLine(Row(label(b), b));
        }

        if (totalRow is not null && rows.Count > 1)
        {
            md.AppendLine(Row("**all**", totalRow));
        }
    }

    private static string Row(string label, Bucket b)
    {
        var cells = new List<string> { label, N(b.Units), N(b.NaUnits) };
        foreach (UnitStatus s in Levels)
        {
            cells.Add($"{N(b.UnitsAtLeast(s))} ({Bucket.Pct(b.ByUnits(s))})");
        }

        cells.Add(N(b.InScopeBytes));
        foreach (UnitStatus s in Levels)
        {
            cells.Add(Bucket.Pct(b.Weighted(s)));
        }

        return "| " + string.Join(" | ", cells) + " |";
    }

    private static void AppendList(StringBuilder md, string title, IReadOnlyList<string> items, string? note)
    {
        md.AppendLine($"### {title} ({N(items.Count)})");
        md.AppendLine();
        if (note is not null)
        {
            md.AppendLine(note);
            md.AppendLine();
        }

        if (items.Count == 0)
        {
            md.AppendLine("None.");
            md.AppendLine();
            return;
        }

        foreach (string i in items.Take(MarkdownListCap))
        {
            md.AppendLine("- " + Cell(i));
        }

        if (items.Count > MarkdownListCap)
        {
            md.AppendLine($"- ... {N(items.Count - MarkdownListCap)} more in `coverage.json`.");
        }

        md.AppendLine();
    }

    public static string Json(CoverageResult r)
    {
        var sb = new StringBuilder();
        IReadOnlyList<UnitState> all = r.Units;
        var slice = all.Where(s => s.Unit!.Slice).ToList();
        sb.Append("{\n");
        sb.Append("  \"format\": \"svm.coverage/1\",\n");
        CoverageInputs i = r.Inputs;
        sb.Append("  \"inputs\": ").Append(Compact(new
        {
            inventory = new { format = i.Inventory.Format, units = i.Inventory.Units.Count, bytes = i.Inventory.Units.Sum(u => u.Weight) },
            assemblies = i.Assemblies.Select(a => a.Name).Order(StringComparer.Ordinal).ToArray(),
            attributes = r.AttributeCount,
            statusFile = new { na = i.Status.Na.Count, units = i.Status.Units.Count },
            specIds = i.Specs.Count,
            scenarios = i.Scenarios.Count,
            runnerReport = i.Report is not null,
            timing = i.AllTimings ? "all" : Scenarios.GateTiming,
        })).Append(",\n");
        sb.Append("  \"summary\": [\n").Append(Buckets([Bucket.Total("all", all), Bucket.Total("slice", slice)])).Append("  ],\n");
        sb.Append("  \"packages\": [\n").Append(Buckets(Bucket.GroupBy(all, s => s.Unit!.Package))).Append("  ],\n");
        sb.Append("  \"kinds\": [\n").Append(Buckets(Bucket.GroupBy(all, s => s.Unit!.Kind))).Append("  ],\n");
        sb.Append("  \"subsystems\": [\n").Append(Buckets(Bucket.GroupBy(all, s => s.Unit!.Subsystem))).Append("  ],\n");
        sb.Append("  \"sliceReasons\": [\n").Append(Buckets(Bucket.GroupBy(slice, s => s.Unit!.SliceReason ?? "?"))).Append("  ],\n");
        sb.Append("  \"classes\": [\n").Append(Buckets(Bucket.GroupBy(all, s => s.Unit!.ClassPath))).Append("  ],\n");
        sb.Append("  \"na\": [\n");
        sb.Append(Lines(i.Status.Na.Select(e => Compact(new
        {
            index = e.Index,
            globs = e.Globs.Select(g => g.Pattern).ToArray(),
            units = r.NaMatches.GetValueOrDefault(e.Index),
            reason = e.Reason,
        }))));
        sb.Append("  ],\n");
        sb.Append("  \"scenarios\": [\n");
        sb.Append(Lines(i.Scenarios.Select(sc => Compact(new
        {
            id = sc.Id,
            covers = sc.Covers.Count,
            golden = r.ScenarioResults.GetValueOrDefault(sc.Id) switch { true => "pass", false => "fail", null => "none" },
        }))));
        sb.Append("  ],\n");
        sb.Append("  \"units\": {\n").Append(UnitLines(all.Where(s => s.Status != UnitStatus.Unported))).Append("  },\n");
        sb.Append("  \"extra\": {\n").Append(UnitLines(r.Extra)).Append("  },\n");
        sb.Append("  \"issues\": {\n");
        sb.Append("    \"errors\": [\n").Append(Lines(r.Errors.Select(Str), 6)).Append("    ],\n");
        sb.Append("    \"warnings\": [\n").Append(Lines(r.Warnings.Select(Str), 6)).Append("    ],\n");
        sb.Append("    \"unknownSpecIds\": [\n").Append(Lines(r.UnknownSpecIds.Select(Str), 6)).Append("    ]\n");
        sb.Append("  }\n");
        sb.Append("}\n");
        return sb.ToString();
    }

    private static string Buckets(IEnumerable<Bucket> buckets) => Lines(buckets.Select(b => Compact(new
    {
        key = b.Key,
        units = b.Units,
        na = b.NaUnits,
        specced = b.UnitsAtLeast(UnitStatus.Specced),
        ported = b.UnitsAtLeast(UnitStatus.Ported),
        verified = b.UnitsAtLeast(UnitStatus.Verified),
        bytes = b.Bytes,
        naBytes = b.NaBytes,
        speccedBytes = b.BytesAtLeast(UnitStatus.Specced),
        portedBytes = b.BytesAtLeast(UnitStatus.Ported),
        verifiedBytes = b.BytesAtLeast(UnitStatus.Verified),
    })));

    private static string UnitLines(IEnumerable<UnitState> units)
    {
        var lines = units.Select(s =>
        {
            var o = new SortedDictionary<string, object>(StringComparer.Ordinal) { ["status"] = UnitStatusText.Text(s.Status) };
            if (s.Specs.Count > 0)
            {
                o["specs"] = s.Specs.ToArray();
            }

            if (s.Ports.Count > 0)
            {
                o["ports"] = s.Ports.ToArray();
            }

            if (s.Generated)
            {
                o["generated"] = true;
            }

            if (s.PassingScenarios.Count > 0)
            {
                o["scenarios"] = s.PassingScenarios.ToArray();
            }

            if (s.NaEntry is { } entry)
            {
                o["na"] = entry;
            }
            else if (s.NaReason is { Length: > 0 } reason)
            {
                o["reason"] = reason;
            }

            if (s.StatusFileNote is { } note)
            {
                o["statusFile"] = note;
            }

            return Str(s.Id) + ": " + Compact(o);
        });
        return Lines(lines);
    }

    private static string Lines(IEnumerable<string> items, int indent = 4)
    {
        var list = items.ToList();
        var sb = new StringBuilder();
        string pad = new(' ', indent);
        for (int k = 0; k < list.Count; k++)
        {
            sb.Append(pad).Append(list[k]).Append(k + 1 < list.Count ? ",\n" : "\n");
        }

        return sb.ToString();
    }

    private static readonly JsonSerializerOptions CompactOptions = new() { WriteIndented = false };

    private static string Compact(object o) => JsonSerializer.Serialize(o, CompactOptions);

    private static string Str(string s) => JsonSerializer.Serialize(s, CompactOptions);

    public const string HistoryHeader =
        "date,commit,units,in_scope_units,in_scope_bytes,na_units,specced_units,ported_units,verified_units," +
        "specced_w,ported_w,verified_w,slice_in_scope_bytes,slice_specced_w,slice_ported_w,slice_verified_w," +
        "extra_units,extra_ported,errors,warnings";

    /// <summary>One history row; percentages (w = weighted by bytes) with two decimals.</summary>
    public static string HistoryRow(CoverageResult r, string date, string commit)
    {
        Bucket t = Bucket.Total("all", r.Units);
        Bucket s = Bucket.Total("slice", r.Units.Where(u => u.Unit!.Slice));
        Bucket e = Bucket.Total("extra", r.Extra);
        var cells = new object[]
        {
            date, commit, t.Units, t.InScopeUnits, t.InScopeBytes, t.NaUnits,
            t.UnitsAtLeast(UnitStatus.Specced), t.UnitsAtLeast(UnitStatus.Ported), t.UnitsAtLeast(UnitStatus.Verified),
            Bucket.PctPlain(t.Weighted(UnitStatus.Specced)), Bucket.PctPlain(t.Weighted(UnitStatus.Ported)), Bucket.PctPlain(t.Weighted(UnitStatus.Verified)),
            s.InScopeBytes,
            Bucket.PctPlain(s.Weighted(UnitStatus.Specced)), Bucket.PctPlain(s.Weighted(UnitStatus.Ported)), Bucket.PctPlain(s.Weighted(UnitStatus.Verified)),
            e.Units, e.UnitsAtLeast(UnitStatus.Ported), r.Errors.Count, r.Warnings.Count,
        };
        return string.Join(",", cells.Select(c => Convert.ToString(c, CultureInfo.InvariantCulture)));
    }

    /// <summary>Adds the row to the history, replacing a row with the same date and commit.</summary>
    public static string UpsertHistory(string? existing, string row)
    {
        var lines = (existing ?? "").Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n')
            .Where(l => l.Length > 0).ToList();
        if (lines.Count == 0 || !string.Equals(lines[0], HistoryHeader, StringComparison.Ordinal))
        {
            lines.RemoveAll(l => l.StartsWith("date,", StringComparison.Ordinal));
            lines.Insert(0, HistoryHeader);
        }

        string key = Key(row);
        int at = lines.FindIndex(1, l => string.Equals(Key(l), key, StringComparison.Ordinal));
        if (at >= 0)
        {
            lines[at] = row;
        }
        else
        {
            lines.Add(row);
        }

        return string.Join("\n", lines) + "\n";

        static string Key(string l)
        {
            string[] c = l.Split(',');
            return c.Length >= 2 ? c[0] + "," + c[1] : l;
        }
    }

    private static string N(long n) => n.ToString("#,0", CultureInfo.InvariantCulture);

    private static string Cell(string s) => s.Replace("|", "\\|", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}
