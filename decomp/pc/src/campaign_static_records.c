/* Termination callbacks registered by the stock executable with atexit. */
struct StaticRecord {
    const void *methods;
    union { unsigned int word; unsigned char byte[4]; } flags;
};

extern void __fastcall set_registered(struct StaticRecord *record, float stack_word);

/* Positive floating zero supplies the integer zero required on the member
   call stack. The global record and both methods tables are distinct inputs. */
#define DESTROY_STATIC_RECORD(Entry, Object, Derived, Base) \
    void destroy_static_record_##Entry(void) \
    { \
        Object.methods = Derived; \
        if (Object.flags.word & 0x8000u) { \
            Object.flags.byte[1] &= 0x7fu; \
            set_registered(&Object, 0.0f); \
        } \
        Object.methods = Base; \
    }

