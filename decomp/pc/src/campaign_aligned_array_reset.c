#include "campaign_array_resize_abi.h"

struct ResetRequest { int element_size, capacity; };

static __forceinline void reset_array(struct Array *array, int width, int capacity, const unsigned short *label)
{
    struct ArraySize bytes;
    struct ArrayTag tag;
    bytes.value = width * capacity;
    array->capacity = capacity;
    array->count = 0;
    tag.text = label;
    array->buffer.bytes = resize_heap->methods->resize(resize_heap, resize_heap->methods, array->buffer, bytes.value, tag);
}

#define RESET_DYNAMIC(Entry, Tag) \
    void __fastcall Entry(struct Array *array, struct ResetRequest request) \
    { \
        reset_array(array, request.element_size, request.capacity, Tag); \
    }
#define RESET_FIXED(Entry, Width, Tag) \
    void __fastcall Entry(struct Array *array, struct ArraySize capacity) \
    { \
        reset_array(array, Width, capacity.value, Tag); \
    }

