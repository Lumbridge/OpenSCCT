/* The named class descriptors retain callbacks for placement construction.
   The base initializer is shared by classes with no additional base work.
   Actor constructors also initialize four inherited fields before installing
   the derived vtable. */
struct PlacementObject {
    const void *const *methods;
    unsigned char actor_fields[0x1cc - 4];
    float initial_values[4];
};

#define PLACE_ACTOR(Type, Base)                                               \
    extern const void *const vtable_##Type[];                                 \
    extern void __fastcall Base(struct PlacementObject *);                    \
    void place_##Type(struct PlacementObject *object)                         \
    {                                                                         \
        if (object) {                                                         \
            Base(object);                                                     \
            object->initial_values[0] = 0.0f;                                 \
            object->initial_values[1] = 0.0f;                                 \
            object->initial_values[2] = 1.0e-8f;                              \
            object->initial_values[3] = 0.0f;                                 \
            object->methods = vtable_##Type;                                  \
        }                                                                     \
    }

#define PLACE_OBJECT(Type, Base)                                              \
    extern const void *const vtable_##Type[];                                 \
    extern void __fastcall Base(struct PlacementObject *);                    \
    void place_##Type(struct PlacementObject *object)                         \
    {                                                                         \
        if (object) {                                                         \
            Base(object);                                                     \
            object->methods = vtable_##Type;                                  \
        }                                                                     \
    }

#define PLACE_DELEGATED(Type, Constructor)                                    \
    extern void __fastcall Constructor(struct PlacementObject *);              \
    void place_##Type(struct PlacementObject *object)                         \
    {                                                                         \
        if (object)                                                           \
            Constructor(object);                                              \
    }

