#include "campaign_array_storage.h"

union ArrayIndexWord {
    int integer;
    float stack_argument;
};

/* The member call receives the receiver in ECX and both index and count
   on the stack. The constant has the integer representation of index zero. */
#define DECLARE_TYPED_REMOVE(Entry) \
    extern void __fastcall remove_typed_##Entry(struct Array *, float index, struct ArraySize count)

#define DESTROY_TYPED_ARRAY(Entry, Remove) \
    void __fastcall destroy_typed_##Entry(struct Array *array) \
    { \
        static const union ArrayIndexWord first = { 0 }; \
        struct ArraySize count; \
        count.value = array->count; \
        remove_typed_##Remove(array, first.stack_argument, count); \
        release_storage(array); \
    }

